func TestBloomFilterFalsePositive(t *testing.T) {
	f := func(data []byte, partFormatVersion uint, maxFalsePositive float64) {
		t.Helper()

		bf := getBloomFilter()
		defer putBloomFilter(bf)
		if err := bf.unmarshal(data, partFormatVersion); err != nil {
			t.Fatalf("unexpected error when unmarshaling bloom filter: %s", err)
		}

		// count the number of false positives on 100K non-existing tokens
		const n = 100_000
		falsePositives := 0
		for i := range n {
			token := fmt.Sprintf("non-existing-token_%d", i)
			tokensHashes := appendTokensHashes(nil, []string{token})
			if bf.containsAll(tokensHashes) {
				falsePositives++
			}
		}
		p := float64(falsePositives) / n
		if p > maxFalsePositive {
			t.Fatalf("too high false positive rate; got %.5f; want %.5f max", p, maxFalsePositive)
		}
		if p == 0 {
			t.Fatalf("unexpected zero false positive rate; the bloom filter is probably too big")
		}
	}

	tokens := make([]string, 20000)
	for i := range tokens {
		tokens[i] = fmt.Sprintf("token_%d", i)
	}
	f(bloomFilterMarshalTokens(nil, tokens), partFormatLatestVersion, 0.0016)
	f(legacyBloomFilterMarshalTokens(nil, tokens), partFormatSBBFVersion-1, 0.0011)
}

