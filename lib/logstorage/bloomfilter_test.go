func TestAppendTokensHashes(t *testing.T) {
	tokens := []string{"foo", "bar", "baz"}
	hashes := appendTokensHashes(nil, tokens)
	if len(hashes) != len(tokens)*bloomFilterTokenHashesCount {
		t.Fatalf("unexpected number of hashes; got %d; want %d", len(hashes), len(tokens)*bloomFilterTokenHashesCount)
	}
	for i, token := range tokens {
		h := xxhash.Sum64String(token)
		if hashes[i*bloomFilterTokenHashesCount] != h {
			t.Fatalf("unexpected token hash for %q; got %X; want %X", token, hashes[i*bloomFilterTokenHashesCount], h)
		}
	}

	hashesFromHashes := appendHashesHashes(nil, tokenizeHashes(nil, tokens))
	if fmt.Sprint(hashes) != fmt.Sprint(hashesFromHashes) {
		t.Fatalf("unexpected hashes from hashes\ngot\n%X\nwant\n%X", hashesFromHashes, hashes)
	}

	// Verify that the existing contents of dst is preserved
	prefix := []uint64{1, 2, 3}
	result := appendTokensHashes(append([]uint64{}, prefix...), tokens)
	if fmt.Sprint(result[:len(prefix)]) != fmt.Sprint(prefix) || fmt.Sprint(result[len(prefix):]) != fmt.Sprint(hashes) {
		t.Fatalf("unexpected result for non-empty dst: %X", result)
	}
	result = appendHashesHashes(append([]uint64{}, prefix...), tokenizeHashes(nil, tokens))
	if fmt.Sprint(result[:len(prefix)]) != fmt.Sprint(prefix) || fmt.Sprint(result[len(prefix):]) != fmt.Sprint(hashes) {
		t.Fatalf("unexpected result for non-empty dst: %X", result)
	}
}

func FuzzBloomFilterNoFalseNegatives(f *testing.F) {
	f.Add("foo bar baz")
	f.Add("")
	f.Add("GET /api/v1/users/12345 status=200 ip=10.1.2.3")
	f.Add("привет мир 你好 世界")
	f.Fuzz(func(t *testing.T, s string) {
		values := []string{s}
		tokens := tokenizeStrings(nil, values)
		hashes := tokenizeHashes(nil, values)
		tokensHashes := appendTokensHashes(nil, tokens)

		// Split block bloom filter
		var bf bloomFilter
		if err := bf.unmarshal(bloomFilterMarshalHashes(nil, hashes), partFormatLatestVersion); err != nil {
			t.Fatalf("cannot unmarshal bloom filter: %s", err)
		}
		if !bf.containsAll(tokensHashes) {
			t.Fatalf("false negative for tokens %q", tokens)
		}
		for _, token := range tokens {
			if !bf.containsAll(appendTokensHashes(nil, []string{token})) {
				t.Fatalf("false negative for token %q", token)
			}
		}

		// Legacy bloom filter
		if err := bf.unmarshal(legacyBloomFilterMarshalTokens(nil, tokens), partFormatSBBFVersion-1); err != nil {
			t.Fatalf("cannot unmarshal legacy bloom filter: %s", err)
		}
		if !bf.containsAll(tokensHashes) {
			t.Fatalf("false negative in legacy bloom filter for tokens %q", tokens)
		}
	})
}

func FuzzBloomFilterUnmarshal(f *testing.F) {
	f.Add([]byte("0123456789abcdef0123456789abcdef"), uint(partFormatLatestVersion), "foo")
	f.Add([]byte("01234567"), uint(partFormatSBBFVersion-1), "foo bar")
	f.Add([]byte{}, uint(0), "")
	f.Fuzz(func(t *testing.T, data []byte, partFormatVersion uint, s string) {
		var bf bloomFilter
		if err := bf.unmarshal(data, partFormatVersion); err != nil {
			return
		}
		// containsAll mustn't panic on arbitrary bloom filter contents
		_ = bf.containsAll(appendTokensHashes(nil, tokenizeStrings(nil, []string{s})))

		if !bf.isLegacy {
			if data2 := bf.marshal(nil); string(data2) != string(data) {
				t.Fatalf("marshal(unmarshal(data)) != data\ngot\n%X\nwant\n%X", data2, data)
			}
		}
	})
}

func TestBloomFilterLegacyBitsLayout(t *testing.T) {
	// The bit idx must be read from the bit idx%64 of the big-endian word idx/64 regardless of the architecture.
	data := "\x00\x00\x00\x00\x00\x00\x02\x01\x80\x00\x00\x00\x00\x00\x00\x00"
	var bf bloomFilter
	if err := bf.unmarshal([]byte(data), partFormatSBBFVersion-1); err != nil {
		t.Fatalf("unexpected error: %s", err)
	}

	// tokenHashes returns hashes for a single token, which check the given bit indexes in the legacy bloom filter.
	tokenHashes := func(idxs ...uint64) []uint64 {
		hashes := make([]uint64, bloomFilterTokenHashesCount)
		for i := 1; i < len(hashes); i++ {
			hashes[i] = idxs[(i-1)%len(idxs)]
		}
		return hashes
	}
	if !bf.containsAll(tokenHashes(0, 9, 64+63)) {
		t.Fatalf("containsAll must return true for the set bits")
	}
	for _, idx := range []uint64{1, 8, 56, 63, 64, 64 + 7, 64 + 56} {
		if bf.containsAll(tokenHashes(0, idx)) {
			t.Fatalf("containsAll must return false for the unset bit %d", idx)
		}
	}
}
