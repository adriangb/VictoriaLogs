// bloomFilterMarshalTokens appends marshaled bloom filter for the unique tokens to dst and returns the result.
func bloomFilterMarshalTokens(dst []byte, tokens []string) []byte {
	t := getHashTokenizer()
	defer putHashTokenizer(t)
	var hashes []uint64
	for _, token := range tokens {
		if h, ok := t.addToken(token); ok {
			hashes = append(hashes, h)
		}
	}
	return bloomFilterMarshalHashes(dst, hashes)
}

// legacyBloomFilterMarshalTokens appends legacy bloom filter for tokens to dst exactly like VictoriaLogs did for parts with FormatVersion < partFormatSBBFVersion.
func legacyBloomFilterMarshalTokens(dst []byte, tokens []string) []byte {
	bitsCount := len(tokens) * bloomFilterBitsPerItem
	bits := make([]uint64, (bitsCount+63)/64)
	maxBits := uint64(len(bits)) * 64
	var buf [8]byte
	hp := (*uint64)(unsafe.Pointer(&buf[0]))
	for _, token := range tokens {
		*hp = xxhash.Sum64(bytesutil.ToUnsafeBytes(token))
		for range bloomFilterHashesCount {
			idx := xxhash.Sum64(buf[:]) % maxBits
			(*hp)++
			bits[idx/64] |= uint64(1) << (idx % 64)
		}
	}
	for _, w := range bits {
		dst = encoding.MarshalUint64(dst, w)
	}
	return dst
}

func TestBloomFilter(t *testing.T) {
	f := func(tokens []string) {
		t.Helper()
		dataTokens := bloomFilterMarshalTokens(nil, tokens)
		hashes := tokenizeHashes(nil, tokens)
		dataHashes := bloomFilterMarshalHashes(nil, hashes)
		if string(dataTokens) != string(dataHashes) {
			t.Fatalf("unexpected marshaled bloom filters from hashes\ngot\n%X\nwant\n%X", dataHashes, dataTokens)
		}

		bf := getBloomFilter()
		defer putBloomFilter(bf)
		if err := bf.unmarshal(dataTokens, partFormatLatestVersion); err != nil {
			t.Fatalf("unexpected error when unmarshaling bloom filter: %s", err)
		}
		if bf.isLegacy {
			t.Fatalf("unexpected legacy bloom filter")
		}
		tokensHashes := appendTokensHashes(nil, tokens)
		if !bf.containsAll(tokensHashes) {
			t.Fatalf("containsAll must return true for the added tokens")
		}
		for _, token := range tokens {
			if !bf.containsAll(appendTokensHashes(nil, []string{token})) {
				t.Fatalf("containsAll must return true for the added token %q", token)
			}
		}

		// marshal must return the original data
		if data := bf.marshal(nil); string(data) != string(dataTokens) {
			t.Fatalf("unexpected marshaled bloom filter\ngot\n%X\nwant\n%X", data, dataTokens)
		}
	}
	f(nil)
	f([]string{"foo"})
	f([]string{"foo", "bar", "baz"})

	// 10k tokens
	tokens := make([]string, 10000)
	for i := range tokens {
		tokens[i] = fmt.Sprintf("token_%d", i)
	}
	f(tokens)
}

func TestBloomFilterLegacy(t *testing.T) {
	f := func(tokens []string) {
		t.Helper()
		data := legacyBloomFilterMarshalTokens(nil, tokens)

		for _, partFormatVersion := range []uint{0, 1, 2, 3} {
			bf := getBloomFilter()
			if err := bf.unmarshal(data, partFormatVersion); err != nil {
				t.Fatalf("unexpected error when unmarshaling legacy bloom filter: %s", err)
			}
			if !bf.isLegacy {
				t.Fatalf("expecting legacy bloom filter for partFormatVersion=%d", partFormatVersion)
			}
			if !bf.containsAll(appendTokensHashes(nil, tokens)) {
				t.Fatalf("containsAll must return true for the added tokens")
			}
			if !bf.containsAll(appendHashesHashes(nil, tokenizeHashes(nil, tokens))) {
				t.Fatalf("containsAll must return true for the added tokens hashes")
			}
			for _, token := range tokens {
				if !bf.containsAll(appendTokensHashes(nil, []string{token})) {
					t.Fatalf("containsAll must return true for the added token %q", token)
				}
			}
			putBloomFilter(bf)
		}
	}
	f(nil)
	f([]string{"foo"})
	f([]string{"foo", "bar", "baz"})

	tokens := make([]string, 10000)
	for i := range tokens {
		tokens[i] = fmt.Sprintf("token_%d", i)
	}
	f(tokens)
}

